								<p class="text-xs font-semibold text-amber-700 uppercase tracking-wider">Higher Secondary GER</p>
								<p class="text-3xl font-bold text-amber-800 mt-1">58.4%</p>
							</div>
						</div>

						<p class="mb-6">
							The data highlights an important concern: while students are entering schools successfully, a large proportion are unable to complete their school education. Economic pressures, social barriers, migration, academic stress, and lack of nearby secondary schools remain major contributors to dropout rates.
						</p>

						<!-- Section 4 -->
						<h3 class="text-2xl font-heading font-bold text-neutral-900 mt-10 mb-4">
							4. Access, Equity, and Inclusion
						</h3>
						<p class="mb-6">
							True progress is measured by the inclusion of the most vulnerable. While gender parity has largely been achieved in primary enrolment, structural barriers persist at higher levels.
						</p>
						<ul class="list-disc pl-6 mb-6 space-y-2">
							<li><strong>Gender and Social Disparities:</strong> Girls consistently achieve higher transition rates than boys at most stages, yet they face rising dropout risks in secondary school due to household duties or safety concerns.</li>
							<li><strong>SC/ST Inclusion:</strong> Access for Scheduled Caste (SC) and Scheduled Tribe (ST) students has improved, with ST upper-primary GER reaching 99.5%. However, these students continue to face learning gaps, scoring lower on average in language and math competencies.</li>
							<li><strong>Children with Special Needs (CwSN):</strong> Schools have made strides in physical accessibility—79.1% of schools now have ramps—but only 33.4% have functional CwSN-friendly toilets.</li>
						</ul>

						<!-- Section 5 -->
						<h3 class="text-2xl font-heading font-bold text-neutral-900 mt-10 mb-4">
							5. Quality of Education and Foundational Literacy and Numeracy (FLN)
						</h3>
						<p class="mb-6">
							The quality of learning is the system's "moral and intellectual anchor". Data from the Annual Status of Education Report (ASER) and PARAKH 2024 suggest a complex recovery:
						</p>
						<ul class="list-disc pl-6 mb-6 space-y-2">
							<li><strong>Learning Recovery:</strong> Reading and arithmetic proficiency in Grade 3 showed a sharp recovery in government schools in 2024, reaching their highest levels in a decade.</li>
							<li><strong>Persistent Gaps:</strong> Despite gains, nearly 50% of Grade 5 children still cannot read a Grade 2 level text. In mathematics, only 37% of Grade 9 students perform at grade level, with significant struggles in algebraic thinking and logical reasoning.</li>
							<li><strong>The Math Hurdle:</strong> Arithmetic remains a weak point across all grades, with students often able to recognize patterns but unable to apply concepts to real-life problem-solving, such as money transactions or unit conversions.</li>
						</ul>

						<!-- Section 6 -->
						<h3 class="text-2xl font-heading font-bold text-neutral-900 mt-10 mb-4">
							6. Teacher Education and Professional Development
						</h3>
						<p class="mb-6">
							India’s 1.01 crore teachers are the front-line instructional leaders, yet they are often burdened by non-teaching duties that consume nearly 14% of their planned teaching days.
						</p>
						<ul class="list-disc pl-6 mb-6 space-y-2">
							<li><strong>Vacancies:</strong> Acute shortages exist in states like Bihar (over 2.08 lakh elementary vacancies) and Jharkhand.</li>
							<li><strong>Training Gaps:</strong> Many teachers struggle with subject-matter knowledge; only 10-15% of candidates qualify the Teacher Eligibility Test (TET).</li>
							<li><strong>The Roadmap:</strong> NEP 2020 mandates a four-year integrated B.Ed. as the minimum qualification and emphasizes Continuous Professional Development (CPD) through platforms like DIKSHA and NISHTHA.</li>
						</ul>

						<!-- Section 7 -->
						<h3 class="text-2xl font-heading font-bold text-neutral-900 mt-10 mb-4">
							7. Infrastructure and Digital Education
						</h3>
						<p class="mb-6">
							The physical and digital readiness of schools is essential for modern pedagogy.
						</p>
						<ul class="list-disc pl-6 mb-6 space-y-2">
							<li><strong>Foundational Facilities:</strong> Electricity coverage has soared from 56% to 91.9% over the decade. Functional girls' toilets are available in 94% of schools.</li>
							<li><strong>Digital Divide:</strong> While 64.7% of schools have computers, only 63.5% have internet connectivity. Rural-urban disparities remain stark, and only 30.6% of schools have functional smart classrooms.</li>
							<li><strong>STEM Readiness:</strong> Nearly 50% of government secondary schools lack functional science labs, confining science education to theoretical textbook learning.</li>
						</ul>

						<!-- Section 8 -->
						<h3 class="text-2xl font-heading font-bold text-neutral-900 mt-10 mb-4">
							8. Vocational Education and Skill Development
						</h3>
						<p class="mb-6">
							NEP 2020 aims for 50% of learners to have exposure to vocational education by 2025.
						</p>
						<ul class="list-disc pl-6 mb-6 space-y-2">
							<li><strong>Early Integration:</strong> Vocational subjects are being introduced from Grade 6 onwards, with a focus on "bagless days" and practical exposure.</li>
							<li><strong>Challenges:</strong> There is a persistent societal stigma viewing vocational paths as "non-academic". Additionally, many schools lack industry-grade equipment and skilled trainers.</li>
							<li><strong>The Future:</strong> The National Credit Framework (NCrF) will allow for seamless credit transfer between academic and vocational streams, making skill-based learning an aspirational pathway.</li>
						</ul>

						<!-- Section 9 -->
						<h3 class="text-2xl font-heading font-bold text-neutral-900 mt-10 mb-4">
							9. Governance and School Management
						</h3>
						<p class="mb-6">
							Governance in Indian education is often fragmented, with overlapping jurisdictions and high administrative vacancies at block and district levels.
						</p>
						<ul class="list-disc pl-6 mb-6 space-y-2">
							<li><strong>School Management Committees (SMCs):</strong> While mandated under the RTE Act, many SMCs struggle with irregular meetings and low participation from marginalized parents.</li>
							<li><strong>School Complexes:</strong> A major recommendation is the operationalization of "School Complexes"—grouping secondary schools with surrounding lower-grade schools to share resources like science labs, libraries, and specialist teachers.</li>
						</ul>

						<!-- Section 10 -->
						<h3 class="text-2xl font-heading font-bold text-neutral-900 mt-10 mb-4">
							10. Assessment and Learning Outcomes
						</h3>
						<p class="mb-6">
							The system is moving from high-stakes, rote-based exams to competency-based assessments.
						</p>
						<ul class="list-disc pl-6 mb-6 space-y-2">
							<li><strong>PARAKH:</strong> This new national assessment centre sets norms for student evaluation, focusing on the application of knowledge.</li>
							<li><strong>Holistic Progress Cards (HPC):</strong> Instead of simple grades, students will receive a 360-degree card capturing their intellectual, social, and emotional growth.</li>
						</ul>

						<!-- Section 11 -->
						<h3 class="text-2xl font-heading font-bold text-neutral-900 mt-10 mb-4">
							11. State-Level Innovations: Models of Success
						</h3>
						<p class="mb-6">
							Several states are leading the way with scalable innovations:
						</p>
						<div class="grid grid-cols-1 md:grid-cols-2 gap-4 mb-8">
							<div class="bg-white border border-neutral-200 p-5 rounded-2xl shadow-sm">
								<h5 class="font-bold text-neutral-900 mb-2">Rajasthan (School Rationalization)</h5>
								<p class="text-sm text-neutral-600 leading-relaxed">Consolidated thousands of small schools into "Adarsh Vidyalayas" (Grade 1-12) to improve teacher deployment, infrastructure access, and retention.</p>
							</div>
							<div class="bg-white border border-neutral-200 p-5 rounded-2xl shadow-sm">
								<h5 class="font-bold text-neutral-900 mb-2">Karnataka (Kalika Chetarike)</h5>
								<p class="text-sm text-neutral-600 leading-relaxed">A successful learning recovery initiative focusing strictly on learning competencies rather than simple textbook syllabus coverage.</p>
							</div>
							<div class="bg-white border border-neutral-200 p-5 rounded-2xl shadow-sm">
								<h5 class="font-bold text-neutral-900 mb-2">Nagaland (Lighthouse Complexes)</h5>
								<p class="text-sm text-neutral-600 leading-relaxed">Uses a hub-and-spoke model to share administrative governance, specialist teachers, and infrastructure across school clusters.</p>
							</div>
							<div class="bg-white border border-neutral-200 p-5 rounded-2xl shadow-sm">
								<h5 class="font-bold text-neutral-900 mb-2">Andhra Pradesh ("We Love Reading")</h5>
								<p class="text-sm text-neutral-600 leading-relaxed">A statewide campaign that dramatically improved reading proficiency through dedicated library periods and community literacy melas.</p>
							</div>
						</div>

						<!-- Section 12 -->
						<h3 class="text-2xl font-heading font-bold text-neutral-900 mt-10 mb-4">
							12. Major Challenges and Bottlenecks
						</h3>
						<p class="mb-6">
							Despite progress, "incremental change will not be sufficient". Key hurdles include:
						</p>
						<ul class="list-disc pl-6 mb-6 space-y-2">
							<li><strong>Fragmented Structure:</strong> Only 5% of schools offer a continuous Grade 1-12 pathway, leading to dropouts during transitions.</li>
							<li><strong>Syllabus Pressure:</strong> Teachers often prioritize "finishing the book" over ensuring children actually understand the concepts.</li>
							<li><strong>The Digital Gap:</strong> More than one-third of schools still lack basic internet, limiting technology-enabled learning.</li>
							<li><strong>Learning Poverty:</strong> Gaps emerging at the primary stage tend to deepen by the middle years, creating a cumulative disadvantage for struggling learners.</li>
						</ul>

						<!-- Section 13 -->
						<h3 class="text-2xl font-heading font-bold text-neutral-900 mt-10 mb-4">
							13. Policy Roadmap and Future Recommendations
						</h3>
						<p class="mb-6">
							To achieve the vision of Viksit Bharat@2047, the system must shift from physical expansion to structural transformation.
						</p>

						<div class="bg-primary-50 border border-primary-100 rounded-2xl p-6 mb-8">
							<h4 class="font-bold text-primary-900 mb-3">Systemic Recommendations</h4>
							<ul class="list-disc pl-6 space-y-2 text-primary-900 text-sm">
								<li><strong>Move to a "Cylindrical" School Structure:</strong> Replace the pyramidal model with composite schools (Grades 1-12) to ensure academic continuity.</li>
								<li><strong>Institutionalize School Complexes:</strong> Enable resource pooling for STEM labs, libraries, and sports facilities across school groups.</li>
								<li><strong>Reform Governance:</strong> Fill block/district level administrative vacancies and shift from compliance-driven inspection to supportive academic mentorship.</li>
							</ul>
						</div>

						<div class="bg-accent-50 border border-accent-100 rounded-2xl p-6 mb-8">
							<h4 class="font-bold text-accent-900 mb-3">Academic Recommendations</h4>
							<ul class="list-disc pl-6 space-y-2 text-accent-900 text-sm">
								<li><strong>Foundational Mastery:</strong> Adopt the Teaching-at-the-Right-Level (TaRL) approach, moving students based on proficiency rather than age.</li>
								<li><strong>Teacher as Leader:</strong> Elevate teacher deployment and ensure subject-specific expertise through merit-based recruitment and continuous professional development.</li>
								<li><strong>Integrate AI and Technology:</strong> Use AI-enabled tools for personalized learning and formative assessments, as seen in Rajasthan’s Shikshak app.</li>
							</ul>
						</div>

						<!-- Conclusion -->
						<h3 class="text-2xl font-heading font-bold text-neutral-900 mt-10 mb-4">
							Conclusion
						</h3>
						<p class="mb-4">
							India’s school education system stands at a transformative moment in its developmental journey. Over the last decade, the country has made substantial progress in expanding educational access, improving school infrastructure, strengthening gender inclusion, and promoting foundational learning. However, the larger challenge now lies in ensuring that every child receives meaningful, equitable, and future-oriented education.
						</p>
						<p class="mb-4">
							The National Education Policy 2020 provides a visionary framework for addressing long-standing structural issues through competency-based learning, teacher empowerment, digital integration, vocational education, and holistic student development. Yet policy success will ultimately depend on effective implementation, sustained public investment, administrative coordination, and active community participation.
						</p>
						<p class="mb-6">
							The future of India’s demographic dividend will depend not merely on increasing enrolment statistics, but on building classrooms that foster creativity, critical thinking, inclusion, and lifelong learning. A strong and equitable school education system is not only essential for economic progress—it is fundamental to building an informed, skilled, and socially responsible nation.
						</p>

