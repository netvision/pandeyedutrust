						<div class="space-y-5 mb-8">
							<div class="border-b border-neutral-100 pb-4">
								<p class="font-bold text-neutral-900 mb-1">Q1. Is SQAAF mandatory for all CBSE schools?</p>
								<p class="mb-0">Yes. All schools affiliated with CBSE must undergo the SQAA process and self-assess every year on the SQAA portal.</p>
							</div>
							<div class="border-b border-neutral-100 pb-4">
								<p class="font-bold text-neutral-900 mb-1">Q2. How is the final score calculated?</p>
								<p class="mb-0">Scores are calculated across 84 standards in 7 domains. The core curriculum domain is worth 40%, while the other 6 domains are worth 10% each.</p>
							</div>
							<div class="border-b border-neutral-100 pb-4">
								<p class="font-bold text-neutral-900 mb-1">Q3. What are the maturity levels in SQAAF?</p>
								<p class="mb-0">Schools are categorized into four levels: Inceptive, Transient, Stable, and Dynamic-Evolving.</p>
							</div>
							<div class="border-b border-neutral-100 pb-4">
								<p class="font-bold text-neutral-900 mb-1">Q4. Who should be part of the Core Learning Team?</p>
								<p class="mb-0">The CLT should include a management representative, the principal, teachers from each level, student representatives, parents, and IT staff.</p>
							</div>
							<div>
								<p class="font-bold text-neutral-900 mb-1">Q5. Does SQAAF replace the affiliation process?</p>
								<p class="mb-0">No. Schools aspiring for affiliation can use SQAAF in offline mode to prepare and evaluate their readiness for affiliation.</p>
